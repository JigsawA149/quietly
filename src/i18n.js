export const DICTIONARIES = { en, es, fr, de, pt, it, hi }

export function makeT(lang) {
  const dict = DICTIONARIES[lang] || en
  return (key, vars) => {
    let value = dict[key]
    if (value === undefined) value = en[key]
    if (value === undefined) return key
    if (typeof value !== 'string' || !vars) return value
    return value.replace(/\{(\w+)\}/g, (match, name) => (vars[name] !== undefined ? String(vars[name]) : match))
  }
}

export function detectLanguage() {
  try {
    const list = navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language]
    for (const entry of list) {
      const code = String(entry || '').slice(0, 2).toLowerCase()
      if (LANGUAGES.some(item => item.code === code)) return code
    }
  } catch (error) { /* fall through */ }
  return 'en'
}

